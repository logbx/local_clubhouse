// Function to get intelligent suggestions based on user input
export const getIntelligentSuggestions = (input: string, currentInterests: string[] = []): string[] => {
  if (!input || input.length < 2) {
    return commonInterests.filter(interest => !currentInterests.includes(interest)).slice(0, 10);
  }

  const searchTerm = input.toLowerCase().trim();
  const suggestions = new Set<string>();

  // Direct matches from common interests
  commonInterests.forEach(interest => {
    if (interest.toLowerCase().includes(searchTerm) && !currentInterests.includes(interest)) {
      suggestions.add(interest);
    }
  });

  // Find relevant categories based on keywords
  const relevantCategories = new Set<keyof typeof interestDatabase>();
  
  Object.entries(keywordToCategory).forEach(([keyword, category]) => {
    if (searchTerm.includes(keyword)) {
      relevantCategories.add(category);
    }
  });

  // Add suggestions from relevant categories
  relevantCategories.forEach(category => {
    interestDatabase[category].forEach(interest => {
      if (interest.toLowerCase().includes(searchTerm) && !currentInterests.includes(interest)) {
        suggestions.add(interest);
      }
    });
  });

  // If no category matches, search all categories for partial matches
  if (suggestions.size < 5) {
    Object.values(interestDatabase).flat().forEach(interest => {
      if (interest.toLowerCase().includes(searchTerm) && !currentInterests.includes(interest)) {
        suggestions.add(interest);
      }
    });
  }

  // Convert to array and limit results
  return Array.from(suggestions).slice(0, 15);
};

